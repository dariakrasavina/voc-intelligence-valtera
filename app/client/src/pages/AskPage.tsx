import { useState } from 'react';
import {
  Alert,
  AlertDescription,
  Badge,
  Button,
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
  GenieQueryVisualization,
  Input,
  useGenieChat,
} from '@databricks/appkit-ui/react';
import { EmptyBlock } from '../components/States';

const SUGGESTED = [
  'Which issues are spiking right now?',
  'Weekly safety complaints for the 2026 Aurora EV',
  'Top complaint topics for EV owners in the last 30 days',
  'Which dealers have the highest share of negative interactions?',
];

export function AskPage() {
  const { messages, status, error, sendMessage, reset } = useGenieChat({ alias: 'voc' });
  const [draft, setDraft] = useState('');
  const busy = status === 'streaming';

  const ask = (q: string) => {
    if (!q.trim() || busy) return;
    sendMessage(q.trim());
    setDraft('');
  };

  return (
    <div className="space-y-4 w-full max-w-5xl mx-auto">
      <div>
        <h2 className="text-xl font-semibold">Ask Genie about customer feedback</h2>
        <p className="text-sm text-muted-foreground">
          Genie Agent &ldquo;Valtera VOC Insights&rdquo; over the gold tables and the mv_voc_metrics metric view (no PII columns).
          Queries run with your own Databricks permissions (on-behalf-of-user).
        </p>
      </div>

      <div className="flex flex-wrap gap-2">
        {SUGGESTED.map((q) => (
          <Button key={q} variant="outline" size="sm" disabled={busy} onClick={() => ask(q)}>
            {q}
          </Button>
        ))}
        {messages.length > 0 && (
          <Button variant="ghost" size="sm" onClick={reset}>New conversation</Button>
        )}
      </div>

      {messages.length === 0 && (
        <EmptyBlock title="Ask a question" description="Try a suggested question, or ask about topics, vehicles, dealers or the escalation queue." />
      )}

      {messages.map((m) => (
        <Card key={m.id} className={m.role === 'user' ? 'bg-muted' : ''}>
          <CardHeader className="pb-2">
            <CardDescription>{m.role === 'user' ? 'You asked' : 'Genie'}</CardDescription>
            {m.role === 'user' && <CardTitle className="text-base">{m.content}</CardTitle>}
          </CardHeader>
          {m.role === 'assistant' && (
            <CardContent className="space-y-3">
              {m.content && <p className="text-sm whitespace-pre-wrap">{m.content}</p>}
              {m.attachments.map((a, i) => (
                <div key={a.attachmentId ?? i} className="space-y-2">
                  {a.text?.content && <p className="text-sm whitespace-pre-wrap">{a.text.content}</p>}
                  {a.query?.query && (
                    <details className="rounded-md border p-2">
                      <summary className="text-xs font-medium cursor-pointer">
                        Generated SQL{a.query.title ? ` · ${a.query.title}` : ''}
                      </summary>
                      <pre className="overflow-auto text-xs mt-2">{a.query.query}</pre>
                    </details>
                  )}
                  {a.query?.statementId && m.queryResults.get(a.query.statementId) && (
                    <GenieQueryVisualization data={m.queryResults.get(a.query.statementId)!} />
                  )}
                  {a.suggestedQuestions && a.suggestedQuestions.length > 0 && (
                    <div className="flex flex-wrap gap-2">
                      {a.suggestedQuestions.map((q) => (
                        <Button key={q} variant="outline" size="sm" disabled={busy} onClick={() => ask(q)}>{q}</Button>
                      ))}
                    </div>
                  )}
                </div>
              ))}
              {m.error && (
                <Alert variant="destructive"><AlertDescription>{m.error}</AlertDescription></Alert>
              )}
              <p className="text-xs text-muted-foreground">
                AI-generated by Genie from the data. Check the generated SQL before relying on the answer.
              </p>
            </CardContent>
          )}
        </Card>
      ))}

      {busy && <p className="text-sm text-muted-foreground">Genie is analyzing the data…</p>}
      {status === 'error' && (
        <Alert variant="destructive"><AlertDescription>{error ?? 'Genie failed. Rephrase the question or try again.'}</AlertDescription></Alert>
      )}

      <form
        className="flex gap-2"
        onSubmit={(e) => {
          e.preventDefault();
          ask(draft);
        }}
      >
        <Input value={draft} onChange={(e) => setDraft(e.target.value)} placeholder="Ask about complaints, safety signals, dealers…" aria-label="Question for Genie" />
        <Button type="submit" disabled={busy || !draft.trim()}>Ask</Button>
        <Badge variant="outline" className="self-center">{status}</Badge>
      </form>
    </div>
  );
}
